"""Original-code oracle for synthetic registry records; developer use only.

This checks the known codec entry/exit spans, not arbitrary application record
accesses. An alternate seed is tested as a representation relation, not claimed
to be an admissible runtime replacement.
"""
import hashlib
from pathlib import Path
import struct

from verify_integrity_codec import HASH, OFFSET, U64, pointer, table


class RegistryConsumerOracle:
    def __init__(self, elf):
        self.image = Path(elf).read_bytes()
        if hashlib.sha256(self.image).hexdigest() != HASH:
            raise ValueError('unexpected offline oracle identity')
        self.records = 0
        self.executions = 0
        self.mismatched_seed_controls = 0

    def execute(self, address, key, contents, encoded_pointer=None):
        from unicorn import Uc, UC_ARCH_X86, UC_MODE_64
        from unicorn import x86_const as r
        mu = Uc(UC_ARCH_X86, UC_MODE_64)
        mu.mem_map(0, 0x700000)
        mu.mem_write(0, self.image)
        mu.mem_map(0x1000000, 0x10000)
        mu.mem_map(0x2000000, 0x100000)
        mu.mem_map(0x3000000, 0x4000)
        if not 0x2000000 <= address <= 0x2100000-336:
            raise ValueError('record is outside synthetic heap')
        frame, slot = 0x1009000, 0x3003000
        mu.reg_write(r.UC_X86_REG_RBP, frame)
        mu.reg_write(r.UC_X86_REG_RSP, frame-0x5000)
        mu.reg_write(r.UC_X86_REG_RFLAGS, 0x202)
        mu.mem_write(frame-0x48, struct.pack('<Q', slot))
        mu.mem_write(address, contents)
        if encoded_pointer is None:
            entry, end = 0x3edebc, 0x3ee383
            mu.reg_write(r.UC_X86_REG_RBX, key)
            mu.mem_write(frame-0x90, struct.pack('<I', key))
            mu.mem_write(frame-0x3128, struct.pack('<Q', address))
            mu.mem_write(frame-0x4128, bytes(8))
        else:
            entry, end = 0x3ee6a1, 0x3eed16
            mu.reg_write(r.UC_X86_REG_R8, slot)
            mu.reg_write(r.UC_X86_REG_RAX, key)
            mu.reg_write(r.UC_X86_REG_R14, encoded_pointer)
            mu.reg_write(r.UC_X86_REG_R9, 8)
        mu.emu_start(entry, end, count=100000)
        if mu.reg_read(r.UC_X86_REG_RIP) != end:
            raise AssertionError('consumer did not reach its checked endpoint')
        self.executions += 1
        return (int.from_bytes(mu.mem_read(slot, 8), 'little'),
                bytes(mu.mem_read(address, 336)))

    def check(self, index, address, key, encoded_pointer, plain, encoded):
        # The inputs here are from the actual setup producer, not generated by
        # the scalar model. This connects producer and independent consumer.
        out_pointer, decoded = self.execute(address, key, encoded, encoded_pointer)
        assert out_pointer == (address-OFFSET) & U64
        assert decoded == plain
        assert encoded_pointer == pointer(address, key)
        assert encoded == table(plain, address, key)

        # Test mutation/re-encoding under an explicit alternate representation.
        # This mutation is a synthetic byte edit, NOT a recovered application
        # mutation consumer; that distinction belongs in the report.
        edited = bytearray(decoded)
        at = (index*37) % (336-8)
        edited[at:at+8] = bytes(b ^ (0x81+j) for j, b in enumerate(edited[at:at+8]))
        edited = bytes(edited)
        alternate = key ^ 0xa5a5a5a5
        new_pointer, new_encoded = self.execute(address, alternate, edited)
        assert new_pointer == pointer(address, alternate)
        assert new_encoded == table(edited, address, alternate)
        final_pointer, final = self.execute(address, alternate, new_encoded, new_pointer)
        assert final_pointer == (address-OFFSET) & U64 and final == edited

        # A seed change without transforming the representation must not be
        # reported as cancellation. Check against the already ELF-validated
        # scalar decoder, avoiding speculative reads through an invalid pointer.
        wrong_address = pointer(encoded_pointer, alternate, True)
        assert wrong_address != address
        self.mismatched_seed_controls += 1
        self.records += 1
