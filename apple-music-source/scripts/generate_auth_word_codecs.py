"""Translate verified source instruction prefixes into owned unsigned C.

Only pinned instructions contribute to the functions. The complete artifact
is hashed for identity, but lookup words are not evaluated. No runtime snapshots,
inferred cryptographic parameters, encoding matrices or model assignments contribute.
The generated code is ordinary arithmetic, not serialized oracle results.
"""
import argparse
import hashlib
import json
from pathlib import Path

from recover_guid_word_consumers import candidates
from scan_auth_substitutions import TARGETS


def emit_expression(candidate):
    z=candidate['z'];word=candidate['word'];result=candidate['expression'];nodes=[];seen=set()
    def visit(node):
        if node.get_id() in seen:return
        seen.add(node.get_id())
        for child in node.children():visit(child)
        assert z.is_bv(node) and 1<=node.size()<=32
        nodes.append(node)
    visit(result);names={};lines=[]
    for node in nodes:
        if z.eq(node,word):names[node.get_id()]='word';continue
        name='v'+str(len(lines));kind=node.decl().kind();children=[names[child.get_id()] for child in node.children()]
        if z.is_bv_value(node):expression='UINT32_C(0x%x)'%node.as_long()
        elif kind==z.Z3_OP_BADD:expression=' + '.join(children)
        elif kind==z.Z3_OP_BMUL:expression=' * '.join(children)
        elif kind==z.Z3_OP_BNOT:expression='~'+children[0]
        elif kind==z.Z3_OP_EXTRACT:
            high,low=node.params();expression=children[0]+' >> '+str(low)
        elif kind==z.Z3_OP_CONCAT:
            parts=[];shift=0
            for child,child_name in reversed(list(zip(node.children(),children))):
                assert shift<32
                parts.append('('+child_name+(' << '+str(shift) if shift else '')+')');shift+=child.size()
            expression=' | '.join(parts)
        else:raise ValueError('unsupported source expression operator')
        if node.size()<32:expression='('+expression+') & UINT32_C(0x%x)'%((1<<node.size())-1)
        lines.append('    uint32_t %s = %s;'%(name,expression));names[node.get_id()]=name
    lines.append('    return '+names[result.get_id()]+';')
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('checkout',type=Path)
    parser.add_argument('--verified-decoders',type=Path,required=True)
    parser.add_argument('--native-directory',type=Path,required=True)
    args=parser.parse_args()
    report=json.loads(args.verified_decoders.read_text());functions=[]
    for module in report['modules']:
        filename,digest=TARGETS[module['target']]
        image=(args.checkout/'rootfs/system/lib64'/filename).read_bytes()
        assert hashlib.sha256(image).hexdigest()==module['artifact_sha256']==digest
        for table in module['tables']:
            if table['status']!='verified source word decoder':continue
            assert table['full_word_injectivity_proved'] and table['original_instruction_comparisons']>=384
            pc=int(table['source_load'],16)
            candidate=next(item for item in candidates(image,pc)
                           if item['end']==int(table['source_decoder_end'],16) and item['output_register']==table['source_output_register'])
            identifier='AMS_AUTH_WORD_%s_%X'%(module['target'].upper(),pc)
            name='word_%s_%x'%(module['target'],pc)
            functions.append(dict(identifier=identifier,name=name,body=emit_expression(candidate),module=module['target'],digest=digest,
                begin=hex(candidate['begin']),end=hex(candidate['end'])))
    assert len(functions)==5
    header='''#ifndef AMS_AUTH_WORD_CODECS_H
#define AMS_AUTH_WORD_CODECS_H
#include <stdint.h>
/* Source instruction word decoders only. No table initialization, complete
 * cipher, device proof, session or authentication provider is implemented.
 * Success returns 1; unsupported IDs/null output return 0 without writing. */
enum ams_auth_word_decoder {
'''+''.join('    %s = %d,\n'%(function['identifier'],index) for index,function in enumerate(functions))+'''};
int ams_auth_word_decode(unsigned decoder,uint32_t word,uint32_t *output);
#endif
'''
    source='''/* Generated by scripts/generate_auth_word_codecs.py from source instruction
 * operands only. No image words, fitted maps, keys or runtime values.
 * Unsigned temporaries preserve the source bitvector widths explicitly.
 * This is a bounded word-operand model, not native-auth closure. */
#include "auth_word_codecs.h"
'''
    for function in functions:
        source+='\n/* %s %s..%s; artifact SHA256 %s */\n'%(function['module'],function['begin'],function['end'],function['digest'])
        source+='static uint32_t %s(uint32_t word){\n%s\n}\n'%(function['name'],function['body'])
    source+='\nint ams_auth_word_decode(unsigned decoder,uint32_t word,uint32_t *output){\n    uint32_t value;\n    if(!output)return 0;\n    switch(decoder){\n'
    for function in functions:source+='    case %s:value=%s(word);break;\n'%(function['identifier'],function['name'])
    source+='    default:return 0;\n    }\n    *output=value;return 1;\n}\n'
    args.native_directory.mkdir(parents=True,exist_ok=True)
    (args.native_directory/'auth_word_codecs.c').write_text(source)
    (args.native_directory/'auth_word_codecs.h').write_text(header)
    print(json.dumps(dict(status='generated source arithmetic',word_decoders=len(functions),table_or_runtime_values_consumed=False)))


if __name__=='__main__':main()
